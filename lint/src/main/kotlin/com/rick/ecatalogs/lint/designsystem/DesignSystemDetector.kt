package com.rick.ecatalogs.lint.designsystem

import com.android.tools.lint.client.api.UElementHandler
import com.android.tools.lint.detector.api.Category
import com.android.tools.lint.detector.api.Detector
import com.android.tools.lint.detector.api.Implementation
import com.android.tools.lint.detector.api.Issue
import com.android.tools.lint.detector.api.JavaContext
import com.android.tools.lint.detector.api.Scope
import com.android.tools.lint.detector.api.Severity
import org.jetbrains.uast.UCallExpression
import org.jetbrains.uast.UElement
import org.jetbrains.uast.UQualifiedReferenceExpression

/**
 * A detector that checks for incorrect usages of Compose Material APIs over equivalents in
 * the E-Catalogs design system (`:data:ui_components:common`).
 */
class DesignSystemDetector : Detector(), Detector.UastScanner {

    override fun getApplicableUastTypes(): List<Class<out UElement>> = listOf(
        UCallExpression::class.java,
        UQualifiedReferenceExpression::class.java,
    )

    override fun createUastHandler(context: JavaContext): UElementHandler =
        object : UElementHandler() {
            override fun visitCallExpression(node: UCallExpression) {
                val name = node.methodName ?: return
                val preferredName = METHOD_NAMES[name] ?: return
                // EcsTheme itself is built on MaterialTheme
                if (context.file.name in ALLOWED_FILES) return
                reportIssue(context, node, name, preferredName)
            }

            override fun visitQualifiedReferenceExpression(node: UQualifiedReferenceExpression) {
                val name = node.asRenderString()
                val preferredName = RECEIVER_NAMES[name] ?: return
                reportIssue(context, node, name, preferredName)
            }
        }

    companion object {
        @JvmField
        val ISSUE: Issue = Issue.create(
            id = "DesignSystem",
            briefDescription = "Design system",
            explanation = "This check highlights calls in code that use Compose Material " +
                "composables or colors instead of the equivalents from the E-Catalogs design " +
                "system module, so every screen follows the app's theme (dark-first palette, " +
                "serif titles).",
            category = Category.CUSTOM_LINT_CHECKS,
            priority = 7,
            severity = Severity.ERROR,
            implementation = Implementation(
                DesignSystemDetector::class.java,
                Scope.JAVA_FILE_SCOPE,
            ),
        )

        // :lint is a JVM module and can't depend on the Android design system module, so the
        // names are hardcoded instead of using function references.
        val METHOD_NAMES = mapOf(
            "MaterialTheme" to "EcsTheme",
            "darkColorScheme" to "EcsTheme",
            "lightColorScheme" to "EcsTheme",
        )
        val RECEIVER_NAMES = mapOf(
            "android.R.color.holo_blue_dark" to "MaterialTheme.colorScheme.primary",
            "android.R.color.darker_gray" to "MaterialTheme.colorScheme.onSurfaceVariant",
        )

        private val ALLOWED_FILES = setOf("EcsTheme.kt")

        fun reportIssue(
            context: JavaContext,
            node: UElement,
            name: String,
            preferredName: String,
        ) {
            context.report(
                ISSUE,
                node,
                context.getLocation(node),
                "Using $name instead of $preferredName",
            )
        }
    }
}
